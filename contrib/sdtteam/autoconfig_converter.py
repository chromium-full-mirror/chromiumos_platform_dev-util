def convert_to_designID_starlark(design_id_info):
    starlark_lines = []
    design_id_list_entries = []
    for design_id in design_id_info:
        line = f'DESIGN_ID_{design_id["design_id"].upper()} = design.create_design_id("{design_id["design_id"]}"'  # Double quotes around design_id
        if design_id["config_override"]:
            line += f', config_design_id_override = "{design_id["config_override"]}"'
        if design_id["model_override"]:
            line += f', model_name_design_id_override = "{design_id["model_override"]}"'
        line += ")"
        if line not in starlark_lines:
            design_id_list_entries.append(
                f'DESIGN_ID_{design_id["design_id"].upper()}'
            )
        starlark_lines.append(line)

    design_id_list_line = f"_DESIGN_ID_LIST = [{', '.join(design_id_list_entries)}]"  # Join the design IDs with commas
    starlark_lines.append("\n" + design_id_list_line + "\n")
    device_brand_list_entries = []
    for design_id in design_id_info:
        line = f'DEVICE_BRAND_{design_id["design_id"].upper()}_{design_id["brand_code"]} = device_brand.create('
        line += f'\n    brand_name = "{design_id["brand_name"]}",'
        if design_id["oem_id"]:  # Check if oem_id is not None
            line += f'\n    oem_id = "{design_id["oem_id"]}",'
        if design_id["brand_code"]:
            line += f'\n    brand_code = "{design_id["brand_code"]}",'
        line += f'\n    design_id = DESIGN_ID_{design_id["design_id"].upper()},'
        line += f"\n    export_oem_info = True,"
        line += "\n)\n"
        device_brand_list_entries.append(
            f'DEVICE_BRAND_{design_id["design_id"].upper()}_{design_id["brand_code"]}'
        )
        starlark_lines.append(line)
    # Create the _DEVICE_BRAND_LIST line (corrected)
    device_brand_list_line = (
        f"_DEVICE_BRAND_LIST = [{', '.join(device_brand_list_entries)}]"
    )
    starlark_lines.append(device_brand_list_line)
    return "\n".join(starlark_lines)


def create_brand_configs_starlark(data):
    brand_configs = []
    if "brandConfigs" in data:
        for config in data["brandConfigs"]:
            brand_id = config["brandId"]["value"]
            whitelabel_tag = None
            if "scanConfig" in config:
                whitelabel_tag = config["scanConfig"].get(
                    "whitelabelTag", None
                )  # Default to empty string if not found
            regulatory_label = config.get(
                "regulatoryLabel", ""
            )  # Default to empty string if not found
            wallpaper = config.get(
                "wallpaper", ""
            )  # Default to empty string if not found

            design_id_mappings = get_designID_info(data)
            design_id, brand_code = None, None
            for design_id_info in design_id_mappings:
                if design_id_info["brand_code"] == brand_id:
                    design_id = design_id_info["design_id"]
                    brand_code = design_id_info["brand_code"]
                    break
            brand_config_line = f"brand_config.create(\n    device_brand_id = DEVICE_BRAND_{design_id.upper()}_{brand_code}.id,"
            if whitelabel_tag:
                brand_config_line += (
                    f'\n    custom_label_tag = "{whitelabel_tag}",'
                )
            if regulatory_label:
                brand_config_line += (
                    f'\n    regulatory_label = "{regulatory_label}",'
                )
            if wallpaper:
                brand_config_line += f'\n    wallpaper = "{wallpaper}",'
            brand_config_line += "\n),"
            brand_configs.append(brand_config_line)

        return "\n".join(
            [
                "_BRAND_CONFIGS = [",
                *brand_configs,  # Unpack the list of brand_config lines
                "]",
            ]
        )
    else:
        return "_BRAND_CONFIGS = []"


