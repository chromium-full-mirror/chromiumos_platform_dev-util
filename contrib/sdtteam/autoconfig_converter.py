def verify_test_starlark(star_path):
    #print(f"++ Inside the verify test starlark function")
    test_pass = False

    # command:   ./screebo/config/bin/gen_config ./screebo/config.star
    # command:  git -C ./screebo/ diff ./generated/
    genconfig_command = [f"{star_path}/config/bin/gen_config",  f"{star_path}/config.star"]
    print(f"Compile the converted Starlar, calling: {genconfig_command}")
    returnerror = 0;
    try:
        result = subprocess.run(genconfig_command, capture_output=True, text=True)
        print("Stdout:\n", result.stdout)
        print("Stderr:\n", result.stderr)
        print("returncode:", result.returncode)
    except subprocess.CalledProcessError as e:
        returnerror = 1
        print(f"Command failed with error: {e.stderr}")
    if returnerror != 0 or result.returncode != 0:
        return test_pass

    jsonproto_check_command = ["git", "-C", f"{star_path}/", "diff", "./generated/"]
    print(f"Compilation is success... \nChenk the generated jsonproto data, calling: {jsonproto_check_command}")
    try:
        result = subprocess.run(jsonproto_check_command, capture_output=True, text=True)
        print("Stdout:\n", result.stdout)
        print("Stderr:\n", result.stderr)
        print("returncode:", result.returncode)
    except subprocess.CalledProcessError as e:
        returnerror = 1
        print(f"Command failed with error: {e.stderr}")

    if returnerror != 0 or result.returncode != 0:
        return test_pass

    if result.stdout == "":
        print("There is no diff in the generated config data after the Starlark conversion.")
        test_pass = True
    else:
        print("Genrated config data differ from before the Starlark conversion.")
        print("To debug or report issue, please double-check on the program/project config.star file, they need manual adjustment with this conversion.")

    return test_pass

