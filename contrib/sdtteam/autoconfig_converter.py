def main():
    parser = argparse.ArgumentParser(description="Convert config.jsonproto to Starlark")
    parser.add_argument('-j', '--boxster_project', help="Path to the project boxster repo folder", required=True)
    parser.add_argument("-v", "--verify", help="Run verification test after Starlark conversion.", action="store_true")
    args = parser.parse_args()

    # Convert *program* repo .jsonproto file to *program* autconfig starlark files

    prog_star_path = args.boxster_project + "/program"
    starlark_output = convert_to_program_signer_starlark(prog_star_path)
    #print(f"{starlark_output}")
    signer_star_path = prog_star_path + "/autoflow"
    signer_star_file = signer_star_path + "/signer_config.star"
    if not os.path.exists(signer_star_path):
        #print(f"{signer_star_path} does not exist, creating it.")
        os.makedirs(signer_star_path)
    print(f"Write the signer configs of the program to file {signer_star_file}.")
    with open(signer_star_file, "w") as output_signer_file:
        output_signer_file.write(starlark_output)

    # Convert project repo .jsonproto file to autoconfig starlark files

    starlark_output = convert_to_components_starlark(args.boxster_project)
    #print(f"{starlark_output}")
    components_star_file = args.boxster_project + "/components_config.star"
    print(f"Write the compnents config to file {components_star_file}.")
    with open(components_star_file, "w") as output_comp_file:
        output_comp_file.write(starlark_output)

    starlark_output = convert_to_fwversions_starlark(args.boxster_project)
    fwversion_star_file = args.boxster_project + "/fw_version_config.star"
    print(f"Write the FW versions config to file {fwversion_star_file}")
    with open(fwversion_star_file, "w") as output_file:
        output_file.write(starlark_output)

    # Run Verification Test after Starlark conversion
    test_pass = False
    test_verdict = "Verification failed."
    if args.verify:
        print(f"...Turned on running verification test after Starlark conversion")
        test_pass = verify_test_starlark(args.boxster_project)
        if test_pass :
            test_verdict = "Verification success."
        print(f"{test_verdict}")

if __name__ == "__main__":
    main()