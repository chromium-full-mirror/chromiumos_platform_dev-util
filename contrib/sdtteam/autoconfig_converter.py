def process_jsondata_fwversion(data):
    """Converts JSON device FW versions data into an internal data structure for generating Starlark format."""
    fw_version_info = {}

    for sw_configs in data.get(
        "softwareConfigs", []
    ):  # Handle missing 'softwareConfigs'
        ap_fw_name = (
            sw_configs.get("firmware", {})
            .get("mainRoPayload", {})
            .get("firmwareImageName", "")
        )
        ap_ro_version = (
            sw_configs.get("firmware", {})
            .get("mainRoPayload", {})
            .get("version", {})
        )
        ap_ro_major_version = ap_ro_version.get("major", 0)
        ap_ro_minor_version = ap_ro_version.get("minor", 0)
        ap_ro_patch_version = ap_ro_version.get("patch", 0)

        ap_rw_major_version, ap_rw_minor_version, ap_rw_patch_version = 0, 0, 0
        if "mainRwPayload" in sw_configs.get("firmware", {}):
            ap_rw_version = sw_configs["firmware"]["mainRwPayload"]["version"]
            ap_rw_major_version = ap_rw_version.get("major", 0)
            ap_rw_minor_version = ap_rw_version.get("minor", 0)
            ap_rw_patch_version = ap_rw_version.get("patch", 0)

        ap_rw_a_hash = (
            sw_configs.get("firmware", {}).get("mainRwAHash", {}).get("digest")
        )

        ec_fw_name = (
            sw_configs.get("firmware", {})
            .get("ecRoPayload", {})
            .get("firmwareImageName", "")
        )
        ec_ro_version = (
            sw_configs.get("firmware", {})
            .get("ecRoPayload", {})
            .get("version", {})
        )
        ec_ro_major_version = ec_ro_version.get("major", 0)
        ec_ro_minor_version = ec_ro_version.get("minor", 0)
        ec_ro_patch_version = ec_ro_version.get("patch", 0)

        ec_rw_major_version, ec_rw_minor_version, ec_rw_patch_version = 0, 0, 0
        if "ecRwPayload" in sw_configs.get("firmware", {}):
            ec_rw_version = sw_configs["firmware"]["ecRwPayload"]["version"]
            ec_rw_major_version = ec_rw_version.get("major", 0)
            ec_rw_minor_version = ec_rw_version.get("minor", 0)
            ec_rw_patch_version = ec_rw_version.get("patch", 0)

        fw_info = {
            "ap_fw_name": ap_fw_name,
            "ap_ro_major_version": ap_ro_major_version,
            "ap_ro_minor_version": ap_ro_minor_version,
            "ap_ro_patch_version": ap_ro_patch_version,
            "ap_rw_major_version": ap_rw_major_version,
            "ap_rw_minor_version": ap_rw_minor_version,
            "ap_rw_patch_version": ap_rw_patch_version,
            "ap_rw_a_hash": ap_rw_a_hash,
            "ec_fw_name": ec_fw_name,
            "ec_ro_major_version": ec_ro_major_version,
            "ec_ro_minor_version": ec_ro_minor_version,
            "ec_ro_patch_version": ec_ro_patch_version,
            "ec_rw_major_version": ec_rw_major_version,
            "ec_rw_minor_version": ec_rw_minor_version,
            "ec_rw_patch_version": ec_rw_patch_version,
        }

        if fw_info not in fw_version_info.values():
            fw_version_info[
                sw_configs.get("designConfigId", {})
                .get("value", "")
                .split(":")[0]
                .upper()
            ] = fw_info
    return fw_version_info


def convert_to_fwversions_starlark(star_path):
    """Top-level function that converts JSON device FW versions data into Starlark fw_version configuration format."""

    config_path = star_path + "/generated/config.jsonproto"

    with open(config_path, "r") as f:
        input_data = json.load(f)

    fwversion_info = process_jsondata_fwversion(input_data)
    project_name = os.path.basename(os.path.normpath(star_path))
    starlark_header = f"""# Software firmware configuration for {project_name}

    load("//config/util/sw_config.star", sc = "sw_config")
"""

    sc_fw_config_string = ""

    for device_name, fw_info in fwversion_info.items():
        ap_ro_version = f"sc.create_fw_version({fw_info['ap_ro_major_version']}, {fw_info['ap_ro_minor_version']}, {fw_info['ap_ro_patch_version']})"

        # Check if all ap_rw version numbers are 0
        if any(
            fw_info[key] != 0
            for key in [
                "ap_rw_major_version",
                "ap_rw_minor_version",
                "ap_rw_patch_version",
            ]
        ):
            ap_rw_version = f"sc.create_fw_version({fw_info['ap_rw_major_version']}, {fw_info['ap_rw_minor_version']}, {fw_info['ap_rw_patch_version']})"
        else:
            ap_rw_version = None

        # Check if all ec_rw version numbers are 0
        if any(
            fw_info[key] != 0
            for key in [
                "ec_rw_major_version",
                "ec_rw_minor_version",
                "ec_rw_patch_version",
            ]
        ):
            ec_rw_version = f"sc.create_fw_version({fw_info['ec_rw_major_version']}, {fw_info['ec_rw_minor_version']}, {fw_info['ec_rw_patch_version']})"
        else:
            ec_rw_version = None

        ec_ro_version = f"sc.create_fw_version({fw_info['ec_ro_major_version']}, {fw_info['ec_ro_minor_version']}, {fw_info['ec_ro_patch_version']})"
        ap_rw_a_hash = fw_info["ap_rw_a_hash"] or "None"

        # Conditionally add ap_rw_version and ec_rw_version if not None
        ap_rw_version_line = (
            f"  ap_rw_version={ap_rw_version},\n"
            if ap_rw_version is not None
            else ""
        )
        ec_rw_version_line = (
            f"  ec_rw_version={ec_rw_version}\n"
            if ec_rw_version is not None
            else ""
        )
        ap_rw_a_hash_line = (
            f"  ap_rw_a_hash={ap_rw_a_hash},\n"
            if ap_rw_a_hash is not None
            else ""
        )
        sc_fw_config_string += (
            f"SC_FW_CONFIG_{device_name} = sc.create_fw_payloads_by_names(\n"
            f"  ap_fw_name='{fw_info['ap_fw_name']}',\n"
            f"  ec_fw_name='{fw_info['ec_fw_name']}',\n"
            f"  ap_ro_version={ap_ro_version},\n"
            + ap_rw_a_hash_line
            + ap_rw_version_line
            + f"  ec_ro_version={ec_ro_version},\n"
            + ec_rw_version_line
            + ")\n"
        )

    return starlark_header + "\n" + sc_fw_config_string


