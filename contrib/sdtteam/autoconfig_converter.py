# ==  Regex for searching the config entries in the star file
# matching line: "        EMRIGHT_BOE = _create_touch_partner("
_CREATE_PARTNER_REGEX = re.compile(r"\s*(.*)\s*=\s*_create_touch_partner(.*)")
# matching line: "            name = "emright_boe","
_NAME_PARTNER_REGEX = re.compile(r'\s*name\s*=\s*"(.*)",(.*)')


# matching line: "AUO = _create_display_partner("
_CREATE_DISP_PARTNER_REGEX = re.compile(
    r"\s*(.*)\s*=\s*_create_display_partner(.*)"
)
# matching line: "            vendor_code = "AUO",","
_NAME_DISP_PARTNER_REGEX = re.compile(r'\s*vendor_code\s*=\s*"(.*)",(.*)')


def get_touch_partner_dict(star_path):
    """Utility to build the dict for mapping touch vendor partner name from jsondata
    to Starlark usage."""
    partner_star = star_path + "/config/util/partner.star"
    # print(f"Load partner star file at {partner_star}")

    with open(partner_star, "r") as f:
        lines = [line.rstrip() for line in f]

    partner_dict = {}
    for idx, line in enumerate(lines):
        mymatch = _CREATE_PARTNER_REGEX.search(line)
        if mymatch:
            # print(f"Found match {mymatch.group(1)} and {mymatch.group(2)}")
            partner_key = mymatch.group(1)
            for i in range(idx, len(lines)):
                mymatch2 = _NAME_PARTNER_REGEX.search(lines[i])
                if mymatch2:
                    partner_name = mymatch2.group(1)
                    partner_dict[partner_name] = partner_key
                    break

    return partner_dict


