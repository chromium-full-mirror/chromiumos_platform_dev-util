def process_jsondata_signer(data):
    """Converts JSON device signer data into Starlark signer configuration format."""
    brand_configs = {}
    design_configs = {}

    # Assuming there is one program in the programList
    device_signer_configs = data["programList"][0]["deviceSignerConfigs"]

    for config in device_signer_configs:
        key_id = config["keyId"]
        if "brandId" in config:
            brand_configs[config["brandId"]["value"]] = key_id
        elif "designId" in config:
            design_configs[config["designId"]["value"]] = key_id

    # Build the Starlark strings
    brand_config_str = "\n    ".join(
        [f'"{brand}": "{key_id}",' for brand, key_id in brand_configs.items()]
    )
    design_config_str = "\n    ".join(
        [
            f'"{design}": "{key_id}",'
            for design, key_id in design_configs.items()
        ]
    )

    starlark_header = """## This file is autogenerated. Please follow <dlm-signer-documentation > for steps to configure the partner configuration

## filename: signer_config.star
## filepath: src/program/<PROGRAM_NAME>/signer_config.star
## <Link to Partner documentation on dlm-signer-documentation>


# Copyright 2020 The Chromium OS Authors. All rights reserved.
# Use of this source code is governed by a BSD-style license that can be
# found in the LICENSE file.

load("//config/util/program.star", program_util = "program")
"""

    starlark_code = f"""{starlark_header}\n_SIGNER_BRAND_CONFIGS = program_util.create_signer_configs_by_brand(
    {{
        {brand_config_str}
    }},
)

_SIGNER_DESIGN_CONFIGS = program_util.create_signer_configs_by_design(
    {{
        {design_config_str}
    }},
)

SIGNER_CONFIGS = _SIGNER_BRAND_CONFIGS + _SIGNER_DESIGN_CONFIGS"""

    return starlark_code


def convert_to_program_signer_starlark(star_path):
    """Top-level function wrapping process_jsondata_signer, taking config path as input."""
    config_path = star_path + "/generated/config.jsonproto"

    with open(config_path, "r") as f:
        input_data = json.load(f)

    starlark_code = process_jsondata_signer(input_data)

    return starlark_code


