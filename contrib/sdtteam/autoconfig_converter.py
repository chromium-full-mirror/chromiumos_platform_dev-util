def process_jsondata_touch(data):
    """Converts JSON device touch component data into internal data-structure for generating as Starlark format."""
    touch_component_types = ["touchpad", "touchscreen"]

    entry_list = []
    # Components configs
    device_components_configs = data["components"]
    # print(f"debug data is {device_components_configs[1]}")
    for config in device_components_configs:
        # print(f"debug key list {list(config.keys())}")
        manufacture = ""
        fw_version = ""
        prod_id = ""
        touch_type = ""
        for key in list(config.keys()):
            if key in touch_component_types:
                manufacture = config["manufacturerId"]["value"]
                fw_version = config[key]["fwVersion"]
                prod_id = config[key]["productId"]
                touch_type = key
                #print(f"{manufacture}, {fw_version}, {prod_id}")
                entry_list.append({'touchType': touch_type, 'manufacturerId': manufacture, 'fwVersion': fw_version, 'productId': prod_id})

    return entry_list

def process_jsondata_display(data):
    """Converts JSON device display component data into internal data-structure for generating as Starlark format."""
    disp_component_types = ["displayPanel"]

    entry_list = []
    # Components configs
    device_components_configs = data["components"]
    # print(f"debug data is {device_components_configs[1]}")
    for config in device_components_configs:
        # print(f"debug key list {list(config.keys())}")
        manufacture = ""
        prod_id = ""
        inch = ""
        wid_px = ""
        hi_px = ""
        pxpi = ""
        for key in list(config.keys()):
            if key in disp_component_types:
                manufacture = config["manufacturerId"]["value"]
                prod_id = config["name"]
                inch = str(int(config[key]["properties"]["diagonalMilliinch"] / 1000))
                hi_px = str(config[key]["properties"]["heightPx"])
                wid_px = str(config[key]["properties"]["widthPx"])
                pxpi = str(config[key]["properties"]["pixelsPerIn"])
                #print(f"{manufacture}, {prod_id}, {inch} {hi_px} {wid_px} {pxpi}")
                entry_list.append({'manufacturerId': manufacture, 'productId': prod_id,
                    'inch': inch, 'heightPx': hi_px, 'widthPx': hi_px, 'pixelsPerIn': pxpi})

    return entry_list

def convert_to_components_starlark(star_path):
    """Top-level function for process_jsondata_touch/display, taking config path as input.
    Converts JSON device touch and display component data into Starlark component configuration format."""
    config_path = star_path + "/generated/config.jsonproto"

    with open(config_path, "r") as f:
        input_data = json.load(f)

    touch_entry_list = process_jsondata_touch(input_data)
    #print(f"Touch Entry list: {touch_entry_list}")
    disp_entry_list = process_jsondata_display(input_data)
    #print(f"Display entry list: {disp_entry_list}")

    partner_touch_dict = get_touch_partner_dict(star_path)
    #print(f"Touch Partner Dict: {partner_touch_dict}")
    partner_disp_dict = get_display_partner_dict(star_path)
    #print(f"Partner Dict: {partner_disp_dict}")

    touch_config_str = ""
    for entry in touch_entry_list:
        touch_config_str += f"""comp.append_{entry['touchType']}(\n\tCOMPONENTS,\n\tCOMPONENT_VENDORS,\n\t""";
        touch_config_str += "touch_vendor = partner.touch." + partner_touch_dict[entry['manufacturerId']] + ",\n\t"
        touch_config_str += 'product_id = "' + entry['productId'] + '",' +"\n\t"
        touch_config_str += 'fw_version = "' + entry['fwVersion'] + '",' +"\n"
        touch_config_str += ")\n"

    disp_config_str = ""
    for entry in disp_entry_list:
        disp_config_str += f"""comp.append_display_panel(\n\tCOMPONENTS,\n\tCOMPONENT_VENDORS,\n\t""";
        disp_config_str += "display_vendor = partner.display_panel." + partner_disp_dict[entry['manufacturerId']] + ",\n\t"
        disp_config_str += 'product_id = "' + entry['productId'] + '",' +"\n\t"
        disp_config_str += 'inch = ' + entry['inch'] +",\n\t"
        disp_config_str += 'width_px = ' + entry['heightPx'] +",\n\t"
        disp_config_str += 'height_px = ' + entry['widthPx'] +",\n\t"
        disp_config_str += 'pixels_per_in = ' + entry['pixelsPerIn'] +",\n"
        disp_config_str += ")\n"



    starlark_header = """# This file is autogenerated. Please follow <partner configuration doc > for steps to configure the partner configuration

## filename: components_config.star
## filepath: src/<$PROGRAM>/<$PROJECT>/components_config.star
## <Link to Partner documentation on component configuration>

load("//config/util/partner.star", "partner")
load("//config/util/component.star", "comp")

COMPONENT_VENDORS = []
COMPONENTS = []

# Component(s)"""

    starlark_code = f"""{starlark_header}\n"""
    starlark_code += touch_config_str
    starlark_code += disp_config_str

    return starlark_code

